const fs = require('fs');
const path = require('path');

const { loadEnvFile } = require('./load-env');

loadEnvFile();

const outputPath = path.resolve(__dirname, '../public/app-config.js');
const DEFAULT_PRODUCTION_SIGNALING_URL = 'https://twindrop-2uzn.onrender.com';
const DEFAULT_PRODUCTION_FRONTEND_URL = 'https://t.sendcore.uz';

function normalizeUrl(value) {
  return typeof value === 'string' && value.trim()
    ? value.trim().replace(/\/+$/, '')
    : null;
}

function isProductionBuild() {
  return process.env.CF_PAGES === '1'
    || Boolean(process.env.CF_PAGES_BRANCH)
    || process.env.CI === 'true'
    || process.env.CI === '1'
    || process.env.NODE_ENV === 'production'
    || process.env.TWINDROP_REQUIRE_PRODUCTION_CONFIG === 'true';
}

function validateOrigin(name, value) {
  let parsed;

  try {
    parsed = new URL(value);
  } catch {
    throw new Error(`${name} must be an absolute http(s) origin`);
  }

  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
    throw new Error(`${name} must use http or https`);
  }

  if (parsed.origin !== value) {
    throw new Error(`${name} must be an origin without a path, query, or hash`);
  }

  if (isProductionBuild() && parsed.protocol !== 'https:') {
    throw new Error(`${name} must use https in production`);
  }

  return parsed.origin;
}

const productionBuild = isProductionBuild();
let signalingUrl = normalizeUrl(process.env.TWINDROP_SIGNALING_URL);
let frontendUrl = normalizeUrl(process.env.TWINDROP_FRONTEND_URL);

if (!signalingUrl && productionBuild) {
  signalingUrl = DEFAULT_PRODUCTION_SIGNALING_URL;
  console.info(`[config] Using production signaling URL ${signalingUrl}`);
}

if (!frontendUrl && productionBuild) {
  frontendUrl = DEFAULT_PRODUCTION_FRONTEND_URL;
  console.info(`[config] Using production frontend URL ${frontendUrl}`);
}

if (signalingUrl) {
  signalingUrl = validateOrigin('TWINDROP_SIGNALING_URL', signalingUrl);
} else {
  console.warn(
    '[config] TWINDROP_SIGNALING_URL is not set. The generated config stays empty; local development uses the page origin.',
  );
}

if (frontendUrl) {
  frontendUrl = validateOrigin('TWINDROP_FRONTEND_URL', frontendUrl);
} else {
  console.warn(
    '[config] TWINDROP_FRONTEND_URL is not set. The generated config stays empty; local development uses the page origin.',
  );
}

const content = `// Generated by scripts/write-client-config.js during the build.
// Empty values are resolved to the page origin only in local development.
window.__TWINDROP_CONFIG__ = {
  signalingUrl: ${signalingUrl ? JSON.stringify(signalingUrl) : "''"},
  frontendUrl: ${frontendUrl ? JSON.stringify(frontendUrl) : "''"}
};\n`;

fs.writeFileSync(outputPath, content, 'utf8');
console.log(`Wrote ${outputPath}`);
